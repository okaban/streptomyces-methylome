"""Build Figures 1-3 of the submission from their panel tiles.

    python scripts/40_main_figures_261013.py      # run from 15_paper_figures/

Panels 1a, 1d, 3b and 3e are regenerated by scripts/panels_261013/panel_mine.py,
which this script calls first. Figures 4-6 are NOT built here: they come from
scripts/newfig_261101/nf_r3_, nf_r4_ and nf_r5_figure_*.py (see figure_manifest.tsv).
panel_F4a.py built panel (a) of an earlier Figure 4 and is no longer called. The other
panels ship as PNG tiles in scripts/panels_261013/ alongside the .py file that
produced each one; those files read their data through artifact markers, which
resolve inside the analysis session and not on a bare filesystem, so they are
kept for provenance rather than re-executed here.

Full width is clamped to 174 mm, the ceiling check_figures.py enforces.
"""
import importlib, json, os, subprocess, sys
import matplotlib.pyplot as plt
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
U = importlib.import_module("00_shared_utils")
U.apply_unified_style()
ROOT = os.path.dirname(HERE)
PAN = os.path.join(HERE, "panels_261013")
OUT = os.path.join(ROOT, "figures_261013")
import os as _os
DPI, GUTTER_MM = int(_os.environ.get('FIG_DPI', 300)), 4

# 2026-11-07 共著者コメント C11/C12/C13/C14/C15 により Figure 3 を 5 パネル→4 パネルに再構成。
#   旧 (a)+旧 (d) -> 新 (a)  占有率（TGGCCGGC を取り込み、マーカー＋Wilson CI に統一）
#   旧 (b) 左      -> 新 (b)  read x instance 組成（右の MH オッズ比フォレストは削除, C13）
#   旧 (c)         -> 削除    REBASE 51/50/0 は本文と Supplementary Table S9c に残す (C15)
#   旧 (e) 左      -> 新 (c)  5' 塩基（別タイル・別パネル文字, C11）
#   旧 (e) 右      -> 新 (d)  局所 GC 五分位（別タイル・別パネル文字, C11）
SPEC = json.loads(r'''{"1": {"width_mm": 174, "ncol": 12, "row_heights_mm": [46, 50, 46], "panels": {"a": {"row": 0, "col": 0, "colspan": 12}, "b": {"row": 1, "col": 0, "colspan": 12}, "c": {"row": 2, "col": 0, "colspan": 12}}}, "3": {"width_mm": 174, "ncol": 12, "row_heights_mm": [56, 46], "panels": {"a": {"row": 0, "col": 0, "colspan": 7}, "b": {"row": 0, "col": 7, "colspan": 5}, "c": {"row": 1, "col": 0, "colspan": 4}, "d": {"row": 1, "col": 4, "colspan": 8}}}}''')
TILES = json.loads(r'''{"1": {"a": "panel_1a.png", "b": "panel_1b.png", "c": "panel_1c.png"}, "3": {"a": "panel_3b.png", "b": "panel_3c.png", "c": "panel_3f1.png", "d": "panel_3f2.png"}}''')


def geom(s):
    mm = DPI / 25.4
    W = int(s["width_mm"] * mm)
    g = int(GUTTER_MM * mm)
    colw = (W - g * (s["ncol"] - 1)) // s["ncol"]
    rowh = [int(h * mm) for h in s["row_heights_mm"]]
    row_y = [sum(rowh[:i]) + g * i for i in range(len(rowh))]
    return W, colw, rowh, row_y, g


def compose(fig_no):
    """Lay the panel tiles on one canvas at the shared module's full width."""
    s = SPEC[str(fig_no)]
    W, colw, rowh, row_y, g = geom(s)
    H = row_y[-1] + rowh[-1]
    fig = plt.figure(figsize=(W / DPI, H / DPI), dpi=DPI)
    for L, p in s["panels"].items():
        w = colw * p["colspan"] + g * (p["colspan"] - 1)
        h = rowh[p["row"]]
        x, y = p["col"] * (colw + g), row_y[p["row"]]
        ax = fig.add_axes([x / W, 1 - (y + h) / H, w / W, h / H])
        ax.imshow(Image.open(os.path.join(PAN, TILES[str(fig_no)][L])).convert("RGBA"))
        # 2026-10-28 著者指示「fig.4c は a と同じように左揃えで」。imshow は
        # アスペクトを保つのでタイルがスロットを埋めないと余白が左右に
        # 等分される（Figure 4 のパネル c は左に 548 px 入っていた）。
        # 'W' に寄せるとその余白が右側だけに出て、各パネルの左端が揃う。
        ax.set_anchor("W")
        ax.set_xticks([]); ax.set_yticks([])
        for sp in ax.spines.values():
            sp.set_visible(False)
        ax.set_axis_off()
        fig.text((x + 0.012 * W) / W, 1 - (y + 0.010 * H) / H, L,
                 fontsize=U.FONT["panel_letter"], fontweight="bold",
                 ha="left", va="top", color="black")
    U.assert_no_text_collisions(fig, f"Figure{fig_no}")
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, f"Figure{fig_no}.png")
    U.save_figure_raster(fig, path, dpi=DPI)
    plt.close(fig)
    px = Image.open(path).size
    assert px[0] / DPI * 25.4 <= U.NAR_WIDTH_MM["full"] + 0.5, (fig_no, px)
    return path, px


if __name__ == "__main__":
    subprocess.run([sys.executable, os.path.join(PAN, "panel_mine.py")], check=True)
    # 2026-11-02 (D166/D167): old Figure 4 was dismantled — its panels (b) and (c)
    # became NF-R3 and NF-R4 and panel (a) a panel of NF-R5. Figure4.png is now
    # written by newfig_261101/nf_r3_figure_261101.py, so figure "4" is gone from
    # SPEC/TILES here; this composer must not write a second, conflicting file.

    # 2026-11-09: Figure 2 は fig2_options_261108/make_revA_261108.py が書く（図版改訂 revA）。
    # ここに "2" を残すと同じ名前の別デザインを後勝ちで上書きし、panel_2*/3a の
    # タイルが Figure 2 のものとして鮮度検査に掛かり続ける。図 4 と同じ理由で外す。
    for n in (1, 3):
        p, (w, h) = compose(n)
        print(f"Figure {n}: {w}x{h} px = {w/DPI*25.4:.1f} x {h/DPI*25.4:.1f} mm -> {p}")
