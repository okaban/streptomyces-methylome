# -*- coding: utf-8 -*-
"""Build the four submission figures from their panel tiles.

    python scripts/40_main_figures_261013.py      # run from 15_paper_figures/

Panels 1a, 1d, 3b, 3e and both 4a/4d are regenerated by
scripts/panels_261013/panel_mine.py, which this script calls first. The other
panels ship as PNG tiles in scripts/panels_261013/ alongside the .py file that
produced each one; those files read their data through artifact markers, which
resolve inside the analysis session and not on a bare filesystem, so they are
kept for provenance rather than re-executed here.

Full width is clamped to 174 mm, the ceiling check_figures.py enforces.
"""
import importlib, json, os, subprocess, sys
import matplotlib.pyplot as plt
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
U = importlib.import_module("00_shared_utils")
U.apply_unified_style()
ROOT = os.path.dirname(HERE)
PAN = os.path.join(HERE, "panels_261013")
OUT = os.path.join(ROOT, "figures_261013")
DPI, GUTTER_MM = 300, 4

SPEC = json.loads(r'''{"1": {"width_mm": 174, "ncol": 12, "row_heights_mm": [52, 46, 42], "panels": {"a": {"row": 0, "col": 0, "colspan": 6}, "b": {"row": 0, "col": 6, "colspan": 6}, "c": {"row": 1, "col": 0, "colspan": 12}, "d": {"row": 2, "col": 0, "colspan": 12}}}, "2": {"width_mm": 174, "ncol": 12, "row_heights_mm": [44, 56], "panels": {"a": {"row": 0, "col": 0, "colspan": 12}, "b": {"row": 1, "col": 0, "colspan": 4}, "c": {"row": 1, "col": 4, "colspan": 4}, "d": {"row": 1, "col": 8, "colspan": 4}}}, "3": {"width_mm": 174, "ncol": 12, "row_heights_mm": [58, 52, 48], "panels": {"a": {"row": 0, "col": 0, "colspan": 6}, "c": {"row": 0, "col": 6, "colspan": 6}, "b": {"row": 1, "col": 0, "colspan": 4}, "e": {"row": 1, "col": 4, "colspan": 4}, "d": {"row": 1, "col": 8, "colspan": 4}, "f": {"row": 2, "col": 0, "colspan": 12}}}, "4": {"width_mm": 174, "ncol": 12, "row_heights_mm": [50, 50], "panels": {"a": {"row": 0, "col": 0, "colspan": 6}, "b": {"row": 0, "col": 6, "colspan": 6}, "c": {"row": 1, "col": 0, "colspan": 6}, "d": {"row": 1, "col": 6, "colspan": 6}}}}''')
TILES = json.loads(r'''{"1": {"a": "panel_1a.png", "b": "panel_1b.png", "c": "panel_1c.png", "d": "panel_1d.png"}, "2": {"a": "panel_2a.png", "b": "panel_2b.png", "c": "panel_2c.png", "d": "panel_2d.png"}, "3": {"a": "panel_3a.png", "b": "panel_3b.png", "c": "panel_3c.png", "d": "panel_3d.png", "e": "panel_3e.png", "f": "panel_3f.png"}, "4": {"a": "panel_F4a.png", "b": "panel_F4b.png", "c": "panel_F4c.png", "d": "panel_F4d.png"}}''')


def geom(s):
    mm = DPI / 25.4
    W = int(s["width_mm"] * mm)
    g = int(GUTTER_MM * mm)
    colw = (W - g * (s["ncol"] - 1)) // s["ncol"]
    rowh = [int(h * mm) for h in s["row_heights_mm"]]
    row_y = [sum(rowh[:i]) + g * i for i in range(len(rowh))]
    return W, colw, rowh, row_y, g


def compose(fig_no):
    """Lay the panel tiles on one canvas at the shared module's full width."""
    s = SPEC[str(fig_no)]
    W, colw, rowh, row_y, g = geom(s)
    H = row_y[-1] + rowh[-1]
    fig = plt.figure(figsize=(W / DPI, H / DPI), dpi=DPI)
    for L, p in s["panels"].items():
        w = colw * p["colspan"] + g * (p["colspan"] - 1)
        h = rowh[p["row"]]
        x, y = p["col"] * (colw + g), row_y[p["row"]]
        ax = fig.add_axes([x / W, 1 - (y + h) / H, w / W, h / H])
        ax.imshow(Image.open(os.path.join(PAN, TILES[str(fig_no)][L])).convert("RGBA"))
        ax.set_xticks([]); ax.set_yticks([])
        for sp in ax.spines.values():
            sp.set_visible(False)
        ax.set_axis_off()
        fig.text((x + 0.012 * W) / W, 1 - (y + 0.010 * H) / H, L,
                 fontsize=U.FONT["panel_letter"], fontweight="bold",
                 ha="left", va="top", color="black")
    U.assert_no_text_collisions(fig, f"Figure{fig_no}")
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, f"Figure{fig_no}.png")
    U.save_figure_raster(fig, path)
    plt.close(fig)
    px = Image.open(path).size
    assert px[0] / DPI * 25.4 <= U.NAR_WIDTH_MM["full"] + 0.5, (fig_no, px)
    return path, px


if __name__ == "__main__":
    subprocess.run([sys.executable, os.path.join(PAN, "panel_mine.py")], check=True)
    for key, src in (("F4a", "panel_4a.png"), ("F4d", "panel_4d.png")):
        Image.open(os.path.join(PAN, src)).save(os.path.join(PAN, f"panel_{key}.png"))

    for n in (1, 2, 3, 4):
        p, (w, h) = compose(n)
        print(f"Figure {n}: {w}x{h} px = {w/DPI*25.4:.1f} x {h/DPI*25.4:.1f} mm -> {p}")
